-- Praat 脚本打包导出（示例脚本）
-- 定义 export(record) 返回 { filename, content }。
-- 本示例生成一段 Praat 脚本：内嵌全部帧数据（PitchTier 点位 + Formant 表），
-- 在 Praat 里运行即可重建同名对象并出图——把 app 的分析结果一键接进 Praat 工作流。
-- record.series.frames 是帧数组：{ t, f0, rmsDb, f1, f2 }（null = 未检出）。
-- 其他格式（MOR/CHAT、自定义 CSV 方言、JSON）同理可写。

function export(record)
  local frames = record.series.frames
  local tier = {}
  local formants = {}
  local lastT = nil

  for i, fr in ipairs(frames) do
    lastT = fr.t
    -- PitchTier：只收有声帧
    if fr.f0 and fr.f0 > 0 then
      table.insert(tier, string.format("%.6f %.6f", fr.t, fr.f0))
    end
    -- Formant 表：t  F1  F2（未检出写 NA，Praat 脚本里跳过）
    local f1 = fr.f1 and string.format("%.2f", fr.f1) or "NA"
    local f2 = fr.f2 and string.format("%.2f", fr.f2) or "NA"
    table.insert(formants, string.format("%.6f %s %s", fr.t, f1, f2))
  end

  local xmin = frames[1] and frames[1].t or 0
  local xmax = lastT or 0

  local out = {}
  table.insert(out, "-- Generated by Simple Voice Tool (record " .. record.id .. ")")
  table.insert(out, "-- 在 Praat 中打开本脚本并 Run，即重建 PitchTier 与 Formant 对象")
  table.insert(out, "")

  -- PitchTier 文本对象
  table.insert(out, 'File type = "ooTextFile"')
  table.insert(out, 'Object class = "PitchTier"')
  table.insert(out, "")
  table.insert(out, string.format("xmin = %.6f", xmin))
  table.insert(out, string.format("xmax = %.6f", xmax))
  table.insert(out, "points: size = " .. #tier)
  for i, line in ipairs(tier) do
    local t, v = line:match("([%d%.]+) ([%d%.]+)")
    table.insert(out, string.format("\tpoints [%d]:", i))
    table.insert(out, "\t\tnumber = " .. t)
    table.insert(out, "\t\tvalue = " .. v)
  end

  -- 重建后的绘图脚本段
  table.insert(out, "")
  table.insert(out, "-- 绘图段：选中 PitchTier 后 Run 到此处即出图")
  table.insert(out, 'Draw: 0, 0, 50, 400, "yes", "no"')

  -- F1/F2 表格（供 Praat spreadsheet 或自定义脚本消费）
  table.insert(out, "")
  table.insert(out, "-- F1/F2 per frame (t, F1 Hz, F2 Hz; NA = not detected)")
  for _, line in ipairs(formants) do
    table.insert(out, "-- " .. line)
  end

  return {
    filename = "voice-" .. (record.id:sub(1, 8)) .. ".praat",
    content = table.concat(out, "\n"),
  }
end
